import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

const projectsJsonPath = path.join(__dirname, '../src/data/projects.json')
const outputPath = path.join(__dirname, '../src/constants/projects.js')

try {
  // Read projects.json
  const projectsData = JSON.parse(fs.readFileSync(projectsJsonPath, 'utf-8'))
  
  // Validate structure
  if (!projectsData.projects || !Array.isArray(projectsData.projects)) {
    throw new Error('Invalid projects.json structure: missing "projects" array')
  }
  
  // Generate JS file content
  const fileContent = `// This file is auto-generated by scripts/build-projects.js
// Do not edit manually - edit src/data/projects.json instead

export const projects = Object.freeze(${JSON.stringify(projectsData.projects, null, 2)})
`
  
  // Ensure output directory exists
  const outputDir = path.dirname(outputPath)
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true })
  }
  
  // Write to projects.js
  fs.writeFileSync(outputPath, fileContent, 'utf-8')
  
  console.log('✅ Projects constant generated successfully')
  console.log(`   Source: src/data/projects.json`)
  console.log(`   Output: src/constants/projects.js`)
  console.log(`   Projects: ${projectsData.projects.length}`)
} catch (error) {
  console.error('❌ Error building projects:', error.message)
  process.exit(1)
}
