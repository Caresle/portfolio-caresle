import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

const experiencesJsonPath = path.join(__dirname, '../src/data/experiences.json')
const outputPath = path.join(__dirname, '../src/constants/experiences.js')

try {
  // Read experiences.json
  const experiencesData = JSON.parse(fs.readFileSync(experiencesJsonPath, 'utf-8'))
  
  // Validate structure
  if (!experiencesData.experiences || !Array.isArray(experiencesData.experiences)) {
    throw new Error('Invalid experiences.json structure: missing "experiences" array')
  }
  
  // Generate JS file content
  const fileContent = `// This file is auto-generated by scripts/build-experiences.js
// Do not edit manually - edit src/data/experiences.json instead

export const experiences = Object.freeze(${JSON.stringify(experiencesData.experiences, null, 2)})
`
  
  // Ensure output directory exists
  const outputDir = path.dirname(outputPath)
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true })
  }
  
  // Write to experiences.js
  fs.writeFileSync(outputPath, fileContent, 'utf-8')
  
  console.log('✅ Experiences constant generated successfully')
  console.log(`   Source: src/data/experiences.json`)
  console.log(`   Output: src/constants/experiences.js`)
  console.log(`   Experiences: ${experiencesData.experiences.length}`)
} catch (error) {
  console.error('❌ Error building experiences:', error.message)
  process.exit(1)
}
